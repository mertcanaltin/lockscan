//! `yarn.lock`, classic (v1) and Berry (v2 and later).
//!
//! Both list one block per resolved package. The block starts at column 0
//! with the specifiers that resolved to it and carries the version on an
//! indented line:
//!
//! ```text
//! lodash@^4.17.0, lodash@^4.17.20:          classic
//!   version "4.17.21"
//!
//! "lodash@npm:^4.17.0, lodash@npm:^4.17.20": Berry
//!   version: 4.17.21
//! ```
//!
//! The name comes from the first specifier. An alias (`my-lodash@npm:lodash@^4`)
//! names the real package after `npm:`, and a protocol that does not come
//! from the registry (`workspace:`, `link:`, `portal:`, `file:`) is skipped.

use super::{is_registry_version, split_name, Package};
use std::collections::BTreeSet;

pub fn parse(text: &str) -> Result<BTreeSet<Package>, String> {
    let mut out = BTreeSet::new();
    let mut current: Option<String> = None;
    for line in text.lines() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if !line.starts_with(' ') {
            current = line
                .trim_end()
                .strip_suffix(':')
                .filter(|header| *header != "__metadata")
                .and_then(package_name);
            continue;
        }
        let Some(name) = &current else {
            continue;
        };
        // Only the block's own `version`, at two spaces, not a dependency's.
        let Some(rest) = line.strip_prefix("  ") else {
            continue;
        };
        let Some(version) = rest
            .strip_prefix("version ")
            .or_else(|| rest.strip_prefix("version: "))
        else {
            continue;
        };
        let version = version.trim().trim_matches('"');
        if is_registry_version(version) {
            out.insert(Package::new(name.clone(), version));
        }
        current = None;
    }
    if out.is_empty() && !text.contains("version") {
        return Err("no package blocks in yarn.lock".into());
    }
    Ok(out)
}

/// The registry name a block header resolves, or None for a block that is
/// not a registry package.
fn package_name(header: &str) -> Option<String> {
    let first = header.split(", ").next()?.trim().trim_matches('"');
    let (name, range) = split_name(first)?;
    if ["workspace:", "link:", "portal:", "file:", "exec:", "git"]
        .iter()
        .any(|p| range.starts_with(p))
    {
        return None;
    }
    if range.contains("://") {
        return None;
    }
    // `alias@npm:real@^1` names the real package; `name@npm:^1` does not.
    if let Some(after) = range.strip_prefix("npm:") {
        if let Some((real, _)) = split_name(after) {
            return Some(real.to_string());
        }
    }
    Some(name.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn names(set: &BTreeSet<Package>) -> Vec<String> {
        set.iter().map(ToString::to_string).collect()
    }

    #[test]
    fn reads_classic() {
        let text = r#"# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.24.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.24.0.tgz#abc"
  dependencies:
    lodash "^4.17.0"

lodash@^4.17.0:
  version "4.17.20"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.20.tgz#def"

my-lodash@npm:lodash@^3.0.0:
  version "3.10.1"

local@file:../local:
  version "1.0.0"

gitdep@git+https://github.com/a/b.git#abc:
  version "1.0.0"

tarball@https://example.com/t.tgz:
  version "1.0.0"
"#;
        assert_eq!(
            names(&parse(text).unwrap()),
            ["@babel/core@7.24.0", "lodash@3.10.1", "lodash@4.17.20"]
        );
    }

    #[test]
    fn reads_berry() {
        let text = r#"# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 8
  cacheKey: 10c0

"@types/node@npm:^20.0.0":
  version: 20.11.0
  resolution: "@types/node@npm:20.11.0"
  dependencies:
    undici-types: "npm:~5.26.4"
  checksum: 10c0/abc
  languageName: node
  linkType: hard

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  languageName: unknown
  linkType: soft

"resolve@patch:resolve@npm%3A^1.22.0#optional!builtin<compat/resolve>":
  version: 1.22.8
  resolution: "resolve@patch:resolve@npm%3A1.22.8#optional!builtin<compat/resolve>::version=1.22.8&hash=c3c19d"
  languageName: node
  linkType: hard

"undici-types@npm:~5.26.4":
  version: 5.26.5
  resolution: "undici-types@npm:5.26.5"
  languageName: node
  linkType: hard
"#;
        assert_eq!(
            names(&parse(text).unwrap()),
            [
                "@types/node@20.11.0",
                "resolve@1.22.8",
                "undici-types@5.26.5"
            ]
        );
    }

    #[test]
    fn does_not_take_a_dependency_line_for_the_version() {
        let text = "a@^1.0.0:\n  dependencies:\n    version \"9.9.9\"\n  version \"1.0.0\"\n";
        assert_eq!(names(&parse(text).unwrap()), ["a@1.0.0"]);
    }
}
